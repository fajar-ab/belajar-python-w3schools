# Untuk menggabungkan dua tupel atau lebih Anda dapat menggunakan + operator:
tuple1 = ("a", "b", "c")
tuple2 = (1, 2, 3)

tuple3 = tuple1 + tuple2
print(tuple3)


# Jika Anda ingin mengalikan isi tupel beberapa kali, Anda dapat menggunakan * operator:
fruits = ("apple", "banana", "cherry")
mytuple = fruits * 2

print(mytuple)
