# frozensetadalah versi tak berubah dari suatu himpunan.
# Seperti himpunan, himpunan ini berisi elemen unik, tidak berurutan, dan tidak dapat diubah.
# Berbeda dengan himpunan, elemen tidak dapat ditambahkan atau dihilangkan dari frozenset.

# Gunakan frozenset() konstruktor untuk membuat frozenset dari iterable apa pun
fruits = frozenset({"apple", "banana", "cherry"})

print(fruits)
print(type(fruits))