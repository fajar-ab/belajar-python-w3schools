# Set digunakan untuk menyimpan beberapa item dalam satu variabel.
thisset = {"apple", "banana", "cherry"}

#  Set tidak berurutan, jadi tidak dapat memastikan di mana pesan item akan muncul
print(thisset)

# Set item tidak berurutan, tidak dapat diubah, dan tidak mengizinkan nilai duplikat


# Untuk menentukan berapa banyak item yang dimiliki suatu set
thisset = {"apple", "banana", "cherry"}

print(len(thisset))

# Dimungkinkan juga untuk menggunakan set() konstruktor untuk membuat himpunan
thisset = set(("apple", "banana", "cherry"))

print(thisset)

